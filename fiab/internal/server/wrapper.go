// nixString renders s as a Nix string literal.
func nixString(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "${", `\${`, "\n", `\n`, "\r", `\r`, "\t", `\t`)
	return `"` + r.Replace(s) + `"`
}

func nixList(ss []string) string {
	parts := make([]string, len(ss))
	for i, s := range ss {
		parts[i] = nixString(s)
	}
	return "[ " + strings.Join(parts, " ") + " ]"
}

var nixIdentRE = func(s string) bool {
	if s == "" {
		return false
	}
	for i, c := range s {
		ok := c == '_' || (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (i > 0 && (c == '-' || c == '\'' || (c >= '0' && c <= '9')))
		if !ok {
			return false
		}
	}
	return true
}

// WrapperParams are the host-specific values templated into a wrapper.
type WrapperParams struct {
	BaseURL   string // e.g. https://cache.example.org (no trailing slash)
	PublicKey string // "" if no signing key is configured
}

// WrapperFlakeNix renders the per-host wrapper flake.nix.
func WrapperFlakeNix(b *Bundle, m *Mode, p WrapperParams) string {
	cacheURL := p.BaseURL + "/cache"
	var sb strings.Builder
	desc := b.Description
	if desc == "" {
		desc = b.Name
	}
	fmt.Fprintf(&sb, "# Generated by flake-in-a-box for %s (mode %s).\n", p.BaseURL, m.Name)
	if m.NeedsFetchClosure {
		sb.WriteString("# Needs the fetch-closure experimental feature, enabled by the consumer\n" +
			"# (nixConfig cannot enable it): --extra-experimental-features fetch-closure\n")
	}
	sb.WriteString("{\n")
	fmt.Fprintf(&sb, "  description = %s;\n\n", nixString(desc+" ("+m.Name+")"))
	sb.WriteString("  nixConfig = {\n")
	fmt.Fprintf(&sb, "    extra-substituters = %s;\n", nixList([]string{cacheURL}))
	if p.PublicKey != "" {
		fmt.Fprintf(&sb, "    extra-trusted-public-keys = %s;\n", nixList([]string{p.PublicKey}))
	}
	if len(m.ExperimentalFeatures) > 0 {
		fmt.Fprintf(&sb, "    extra-experimental-features = %s;\n", nixList(m.ExperimentalFeatures))
	}
	sb.WriteString("  };\n\n")
	fmt.Fprintf(&sb, "  inputs.bundle.url = %s;\n\n", nixString(p.BaseURL+"/"+m.Dist))
	switch m.Kind {
	case "lib":
		sb.WriteString("  outputs = { self, bundle }:\n")
		fmt.Fprintf(&sb, "    bundle.lib.mkOutputs { cacheUrl = %s; };\n", nixString(cacheURL))
	case "passthrough":
		sb.WriteString("  outputs = { self, bundle }: {\n")
		outs := append([]string(nil), m.Outputs...)
		sort.Strings(outs)
		for _, o := range outs {
			if nixIdentRE(o) {
				fmt.Fprintf(&sb, "    %s = bundle.%s;\n", o, o)
			} else {
				fmt.Fprintf(&sb, "    %s = bundle.%s;\n", nixString(o), nixString(o))
			}
		}
		sb.WriteString("  };\n")
	}
	sb.WriteString("}\n")
	return sb.String()
}

type lockFile struct {
	Nodes   map[string]map[string]json.RawMessage `json:"nodes"`
	Root    string                                `json:"root"`
	Version int                                   `json:"version"`
}

// WrapperFlakeLock renders a complete flake.lock for the wrapper: the main
// flake is locked by URL and NAR hash, and the main flake's own lock nodes
// are grafted below it so no re-locking is needed.
func WrapperFlakeLock(b *Bundle, m *Mode, p WrapperParams) ([]byte, error) {
	url := p.BaseURL + "/" + m.Dist
	locked := map[string]any{"type": "tarball", "url": url, "narHash": m.NarHash}
	if m.LastModified != 0 {
		locked["lastModified"] = m.LastModified
	}
	bundleNode := map[string]any{
		"locked":   locked,
		"original": map[string]any{"type": "tarball", "url": url},
	}
	nodes := map[string]any{}
	if len(m.Lock) > 0 {
		var inner lockFile
		if err := json.Unmarshal(m.Lock, &inner); err != nil {
			return nil, fmt.Errorf("mode %s: lock: %w", m.Name, err)
		}
		rename := func(n string) string { return "bundle_" + n }
		remapInputs := func(raw json.RawMessage) (map[string]any, error) {
			var ins map[string]json.RawMessage
			if err := json.Unmarshal(raw, &ins); err != nil {
				return nil, err
			}
			out := map[string]any{}
			for k, v := range ins {
				var s string
				if json.Unmarshal(v, &s) == nil {
					out[k] = rename(s)
					continue
				}
				var path []string
				if err := json.Unmarshal(v, &path); err != nil {
					return nil, err
				}
				out[k] = append([]string{"bundle"}, path...)
			}
			return out, nil
		}
		for name, node := range inner.Nodes {
			if name == inner.Root {
				if ins, ok := node["inputs"]; ok {
					r, err := remapInputs(ins)
					if err != nil {
						return nil, err
					}
					bundleNode["inputs"] = r
				}
				continue
			}
			n := map[string]any{}
			for k, v := range node {
				if k == "inputs" {
					r, err := remapInputs(v)
					if err != nil {
						return nil, err
					}
					n[k] = r
				} else {
					n[k] = v
				}
			}
			nodes[rename(name)] = n
		}
	}
	nodes["bundle"] = bundleNode
	nodes["root"] = map[string]any{"inputs": map[string]any{"bundle": "bundle"}}
	out, err := json.MarshalIndent(map[string]any{"nodes": nodes, "root": "root", "version": 7}, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(out, '\n'), nil
}

// TarGz builds a deterministic gzipped tarball holding files under a
// single top-level directory.
func TarGz(top string, files map[string][]byte, mtime time.Time) ([]byte, error) {
	var buf bytes.Buffer
	zw, _ := gzip.NewWriterLevel(&buf, gzip.BestCompression)
	zw.ModTime = time.Unix(0, 0)
	tw := tar.NewWriter(zw)
	hdr := func(h *tar.Header) error {
		h.ModTime = mtime
		h.Uname, h.Gname = "", ""
		h.Format = tar.FormatPAX
		return tw.WriteHeader(h)
	}
	if err := hdr(&tar.Header{Name: top + "/", Mode: 0o755, Typeflag: tar.TypeDir}); err != nil {
		return nil, err
	}
	names := make([]string, 0, len(files))
	for n := range files {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		data := files[n]
		if err := hdr(&tar.Header{Name: top + "/" + n, Mode: 0o644, Size: int64(len(data)), Typeflag: tar.TypeReg}); err != nil {
			return nil, err
		}
		if _, err := tw.Write(data); err != nil {
			return nil, err
		}
	}
	if err := tw.Close(); err != nil {
		return nil, err
	}
	if err := zw.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
